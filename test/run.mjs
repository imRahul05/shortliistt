import { JOB, RESUME } from './fixtures.mjs';
import { analyzeJob, matchJob } from '../lib/matcher.js';
import { parseResumeModel, modelToText, modelSections, renderResumeHTML, addSkills, reorderSkills, prioritizeBullets, templateSummary } from '../lib/resume-model.js';
import { cleanResumeText } from '../lib/resume-parser.js';
const text = cleanResumeText(RESUME);
const model = parseResumeModel(text);
console.log('name:', model.name, '| headline:', model.headline, '| contact:', model.contact);
console.log('sections:', model.sections.map(s => `${s.title}(${s.kind})`).join(', '));
const jobA = analyzeJob(JOB);
console.log('years:', jobA.years, 'degree:', jobA.degree?.label, 'seniority:', jobA.seniority?.level);
const m = matchJob(jobA, { text, sections: modelSections(model), profile: {} });
console.log('SCORE', m.score, m.verdict, JSON.stringify(m.parts));
for (const s of m.skills) console.log(`  ${s.importance.padEnd(9)} ${s.status.padEnd(8)} ${s.name}${s.via ? ' via ' + s.via : ''} w=${s.weight.toFixed(2)} [${s.tiers}]`);
console.log('years', m.years); console.log('edu', m.education);
console.log('keywords', m.keywords.map(k => (k.found ? '+' : '-') + k.word).join(' '));
console.log('SUGGESTIONS'); m.suggestions.forEach(s => console.log(' ', s.level, s.text));
addSkills(model, ['Kafka', 'PostgreSQL', 'Kubernetes']); reorderSkills(model, ['Java','Spring Boot','AWS','Docker']); prioritizeBullets(model, jobA);
console.log(model.sections.find(s=>s.kind==='skills').body);
console.log(model.sections.find(s=>s.kind==='experience').body);
const m2 = matchJob(jobA, { text: modelToText(model), sections: modelSections(model), profile: {} });
console.log('AFTER TAILOR', m2.score);
console.log(templateSummary({ profile: {}, match: m2, jobA, model }));
console.log(renderResumeHTML(model).slice(0, 600));
