export const SKILL_BY_NAME = new Map(SKILLS.map(s => [s.name, s]));

const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function aliasPattern(a, nf) {
  let p = esc(a).replace(/\s+/g, '[\\s\\-]*');
  if (/[a-z]$/.test(a) && a.length > 3 && !a.endsWith('s')) p += '(?:s|es)?';
  if (nf) p += `(?![\\s\\-]*(?:${nf}))`;
  return p;
}

// Pre-compile one case-insensitive regex per skill (plus optional case-sensitive extra).
export const MATCHERS = SKILLS.map(s => {
  const alts = [...new Set(s.aliases)].sort((a, b) => b.length - a.length).map(a => aliasPattern(a, s.nf));
  return {
    skill: s,
    ci: alts.length ? new RegExp(`(?<![a-z0-9_@.#])(?:${alts.join('|')})(?![a-z0-9+#_])`, 'gi') : null,
    cs: s.re ? new RegExp(s.re.source, s.re.flags.includes('g') ? s.re.flags : s.re.flags + 'g') : null,
  };
});
