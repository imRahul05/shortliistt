// Skill taxonomy used for strict, deterministic matching (no AI).
// S(name, category, aliases, options)
//   fam: skills in the same family give partial credit for each other (e.g. MySQL ~ PostgreSQL)
//   imp: having this skill implies these skills (e.g. Next.js -> React)
//   re:  extra case-sensitive regex (for ambiguous names like C, R, Go, REST)
//   nf:  alias must NOT be followed by this word (e.g. React not followed by "native")
//   generic: broad/soft skill, counts with lower weight
// Skills with a case-sensitive `re` don't get their bare name as a case-insensitive alias (avoids 'go to', 'R&D', 'solid').
const S = (name, cat, aliases = [], o = {}) => ({ name, cat, aliases: o.re ? aliases : [name.toLowerCase(), ...aliases], ...o });

